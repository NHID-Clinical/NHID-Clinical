#!/usr/bin/env python3
"""
Fill the PDF metadata on the built Downloads page
=================================================
specs/index.html carries one placeholder per document:

    <span class="pdf-meta" data-pdf="/specs/NHID-Clinical-Playbook.pdf">PDF</span>

The repository page keeps the placeholder on purpose: the maintained PDFs are
regenerated by `scripts/generate_pdfs.py` whenever a published count moves, so
sizes and dates written into the page would drift the same day. This script
runs inside `scripts/build_pages_site.sh` against the assembled `_site/` copy
and writes "24 pages · 244 KB · 25 Oct 2026" from the files actually shipped.

Page count reads the `/Type /Page` objects (checked against pdfinfo for all
eight documents), size is the file's, the date is the PDF's own /CreationDate.
A placeholder whose PDF is missing fails the build: a download card for a
file that is not there is the defect this page had in October 2026.

Usage:
    python scripts/fill_download_meta.py _site
"""
from __future__ import annotations

import re
import sys
from datetime import datetime
from pathlib import Path

PLACEHOLDER = re.compile(r'(<span class="pdf-meta" data-pdf="([^"]+)">)[^<]*(</span>)')


def pdf_meta(path: Path) -> str:
    data = path.read_bytes()
    pages = len(re.findall(rb"/Type\s*/Page(?![s/])", data))
    counts = [int(c) for c in re.findall(rb"/Type\s*/Pages[^>]*?/Count\s+(\d+)", data, re.S)]
    if counts:
        pages = max(counts)
    size = len(data)
    size_text = f"{size / 1024 / 1024:.1f} MB" if size >= 1024 * 1024 else f"{size // 1024} KB"
    m = re.search(rb"/CreationDate\s*\(D:(\d{8})", data)
    date_text = datetime.strptime(m.group(1).decode(), "%Y%m%d").strftime("%-d %b %Y") if m else None
    parts = [f"{pages} page{'s' if pages != 1 else ''}" if pages else None, size_text, date_text]
    return " · ".join(p for p in parts if p)


def fill(site_dir: Path) -> int:
    page = site_dir / "specs" / "index.html"
    html = page.read_text(encoding="utf-8")
    missing, filled = [], 0

    def sub(m: re.Match) -> str:
        nonlocal filled
        rel = m.group(2).lstrip("/")
        pdf = site_dir / rel
        if not pdf.is_file():
            missing.append(rel)
            return m.group(0)
        filled += 1
        return m.group(1) + pdf_meta(pdf) + m.group(3)

    html = PLACEHOLDER.sub(sub, html)
    if missing:
        raise SystemExit(f"DOWNLOAD META FAIL: placeholders point at PDFs that are not in the build: {missing}")
    page.write_text(html, encoding="utf-8")
    return filled


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit("usage: fill_download_meta.py <site_dir>")
    n = fill(Path(sys.argv[1]))
    print(f"Download metadata filled for {n} document(s)")
